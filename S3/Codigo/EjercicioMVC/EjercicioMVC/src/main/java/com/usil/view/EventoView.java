    private void iniciarTabla() {
        modeloTabla = new DefaultTableModel(new Object[]{"ID", "Nombre", "Fecha", "Lugar", "Categoria"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblEventos.setModel(modeloTabla);
    }

    private void refrescarCombo() {
        cmbCategoria.removeAllItems();
        List<Categoria> categorias = categoriaController.listarCategorias();
        if (categorias.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Registre primero una categoria antes de crear un evento", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
        for (Categoria categoria : categorias) {
            cmbCategoria.addItem(categoria);
        }
    }

    private void refrescarTabla() {
        modeloTabla.setRowCount(0);
        List<Evento> eventos = eventoController.listarEventos();
        for (Evento evento : eventos) {
            modeloTabla.addRow(new Object[]{evento.getId(), evento.getNombre(), evento.getFecha(),
                evento.getLugar(), evento.getCategoria() != null ? evento.getCategoria().getNombre() : ""});
        }
    }

    private void cargarSeleccion() {
        int fila = tblEventos.getSelectedRow();
        int id = (int) modeloTabla.getValueAt(fila, 0);
        Evento evento = eventoController.buscarPorId(id);
        if (evento == null) {
            return;
        }
        txtId.setText(String.valueOf(evento.getId()));
        txtNombre.setText(evento.getNombre());
        txtFecha.setText(evento.getFecha());
        txtLugar.setText(evento.getLugar());
        if (evento.getCategoria() != null) {
            cmbCategoria.setSelectedItem(evento.getCategoria());
        }
    }

    private void limpiarFormulario() {
        txtId.setText("");
        txtNombre.setText("");
        txtFecha.setText("");
        txtLugar.setText("");
        if (cmbCategoria.getItemCount() > 0) {
            cmbCategoria.setSelectedIndex(0);
        }
        tblEventos.clearSelection();
    }

