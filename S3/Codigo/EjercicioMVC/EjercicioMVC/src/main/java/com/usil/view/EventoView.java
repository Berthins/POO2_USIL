    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        Categoria categoria = (Categoria) cmbCategoria.getSelectedItem();
        try {
            eventoController.registrarEvento(txtNombre.getText().trim(), txtFecha.getText().trim(), txtLugar.getText().trim(), categoria);
            refrescarTabla();
            limpiarFormulario();
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Datos invalidos", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un evento de la tabla", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Categoria categoria = (Categoria) cmbCategoria.getSelectedItem();
        try {
            int id = Integer.parseInt(txtId.getText().trim());
            boolean actualizado = eventoController.actualizarEvento(id, txtNombre.getText().trim(), txtFecha.getText().trim(), txtLugar.getText().trim(), categoria);
            if (!actualizado) {
                JOptionPane.showMessageDialog(this, "No se encontro el evento", "Aviso", JOptionPane.WARNING_MESSAGE);
            }
            refrescarTabla();
            limpiarFormulario();
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Datos invalidos", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un evento de la tabla", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "Desea eliminar el evento seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            int id = Integer.parseInt(txtId.getText().trim());
            eventoController.eliminarEvento(id);
            refrescarTabla();
            limpiarFormulario();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        // TODO add your handling code here:
        limpiarFormulario();
    }//GEN-LAST:event_btnLimpiarActionPerformed

